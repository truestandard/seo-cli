const profileJSON = `{"project":"taffy","version":3,"digest":"0123456789abcdef0123","stored":{"voice":{"reader":"nurses"}},
	"effective":{"voice":{"reader":"nurses","tone":"plain and direct","grade_max":7,"person":"you","banned_words":["unlock"],"banned_punctuation":["—"]},
		"facts":{"approved":[{"claim":"Taffy reads one report a month for free.","source":"https://taffy.test/pricing"}],"banned_claims":["diagnoses disease"],"pricing":null,"free_or_trial":null},
		"cta":{"default":{"path":"/signup","label":"Try Taffy"},"by_format":{"comparison":{"path":"/switch","label":"Switch"}}},
		"page_types":["guide","comparison"],
		"qa":{"pass_score":32,"min_area":3,"max_attempts":3,"disabled":["cta_fits"],"criteria":[{"id":"plain_words","area":"voice","scope":"paragraph","hard_fail":true,"question":"Plain | short?"}]},
		"adapters":[{"name":"render","command":"bin/rails test","stage":"check","hard_fail":true}],
		"links":{"min_inbound":1,"hubs":["/guides"]},"repo":{"path":"~/code/ai/taffy","pages_glob":null,"sitemap_url":null}}}`

func decodeProfile(t *testing.T) map[string]any {
	t.Helper()
	var data map[string]any
	if err := json.Unmarshal([]byte(profileJSON), &data); err != nil {
		t.Fatal(err)
	}
	return data
}

func TestProfileLines(t *testing.T) {
	data := decodeProfile(t)
	out := strings.Join(profileLines(data), "\n")
	for _, want := range []string{"profile version 3 for taffy (digest 0123456789ab)", "reader: nurses", "banned words 1", "approved facts 1", "page types: guide, comparison", "plain_words", "render"} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q in:\n%s", want, out)
		}
	}
	data["changed"] = false
	if out := strings.Join(profileLines(data), "\n"); !strings.Contains(out, "nothing changed; profile stays at version 3") {
		t.Errorf("unchanged line:\n%s", out)
	}
}

