func TestProfileCommands(t *testing.T) {
	type call struct {
		method string
		path   string
		body   map[string]any
	}
	var calls []call
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		raw, _ := io.ReadAll(r.Body)
		payload := map[string]any{}
		if len(raw) > 0 {
			_ = json.Unmarshal(raw, &payload)
		}
		calls = append(calls, call{method: r.Method, path: r.URL.Path, body: payload})
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte(profileJSON))
	}))
	defer server.Close()
	t.Setenv(config.EnvConfigDir, t.TempDir())
	dir := t.TempDir()
	dataFile := filepath.Join(dir, "data.json")
	yamlFile := filepath.Join(dir, "taffy.yml")
	out := filepath.Join(dir, "repo", ".claude", "seo-profile.md")
	if err := os.WriteFile(dataFile, []byte(`{"voice":{"reader":"nurses"}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(yamlFile, []byte("voice:\n  reader: nurses\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	runs := [][]string{
		{"profile"},
		{"profile", "set", "--file", dataFile},
		{"profile", "set", "--file", dataFile, "--replace"},
		{"profile", "import", yamlFile},
		{"profile", "pull", "--out", out},
	}
	for _, args := range runs {
		flagDryRun = false
		root := newRootCmd()
		root.SetOut(io.Discard)
		root.SetArgs(append([]string{"--api-url", server.URL, "--token", "seo_test", "--project", "taffy", "--quiet"}, args...))
		if err := root.Execute(); err != nil {
			t.Fatalf("%v: %v", args, err)
		}
	}

	if len(calls) != 5 {
		t.Fatalf("want 5 calls, got %d", len(calls))
	}
	if calls[0].method != http.MethodGet || calls[0].path != "/api/v1/projects/taffy/profile" {
		t.Errorf("plain profile should read: %+v", calls[0])
	}
	if calls[1].method != http.MethodPatch || calls[1].body["merge"] != true || calls[1].body["data"].(map[string]any)["voice"] == nil {
		t.Errorf("set should merge the file's keys: %+v", calls[1])
	}
	if calls[2].body["merge"] != false {
		t.Errorf("--replace should send merge false: %+v", calls[2])
	}
	if calls[3].method != http.MethodPost || calls[3].path != "/api/v1/projects/taffy/profile/import" || calls[3].body["yaml"] != "voice:\n  reader: nurses\n" {
		t.Errorf("import should post the yaml text: %+v", calls[3])
	}
	written, err := os.ReadFile(out)
	if err != nil {
		t.Fatalf("pull should write the copy: %v", err)
	}
	if !strings.HasPrefix(string(written), "<!-- Generated by `seo profile pull`") {
		t.Errorf("copy header:\n%s", written)
	}
}

func TestProfileSetNeedsAJSONObject(t *testing.T) {
	t.Setenv(config.EnvConfigDir, t.TempDir())
	bad := filepath.Join(t.TempDir(), "bad.json")
	if err := os.WriteFile(bad, []byte(`["not", "an", "object"]`), 0o644); err != nil {
		t.Fatal(err)
	}
	for _, args := range [][]string{{"profile", "set"}, {"profile", "set", "--file", bad}} {
		root := newRootCmd()
		root.SetOut(io.Discard)
		root.SetErr(io.Discard)
		root.SetArgs(append([]string{"--api-url", "http://127.0.0.1:1", "--token", "seo_test", "--project", "taffy", "--quiet"}, args...))
		if err := root.Execute(); err == nil || !strings.Contains(err.Error(), "usage") && !strings.Contains(err.Error(), "JSON object") {
			t.Errorf("%v: want a usage error, got %v", args, err)
		}
	}
}
